V3F VIOManager::getInterpolatedPixel(cv::Mat img, V2D pc)
{
  if (!bilinearInFrame(img, pc)) return V3F::Zero();
  // The float-coordinate vikit sampler truncates after conversion. Use the
  // same representation for its bounds check on monochrome images.
  if (img.type() == CV_8UC1)
  {
    const Vector2f px = pc.cast<float>();
    if (!bilinearInFrame(img, px)) return V3F::Zero();
    return V3F::Constant(vk::interpolateMat_8u(img, px.x(), px.y()));
  }
  if (img.type() != CV_8UC3) return V3F::Zero();
  const int x = static_cast<int>(pc.x()), y = static_cast<int>(pc.y());
  const float dx = pc.x() - x, dy = pc.y() - y;
  const cv::Vec3b* top = img.ptr<cv::Vec3b>(y) + x;
  const cv::Vec3b* bottom = img.ptr<cv::Vec3b>(y + 1) + x;
  V3F pixel;
  for (int c = 0; c < 3; ++c)
    pixel[c] = (1-dy) * ((1-dx)*top[0][c] + dx*top[1][c]) + dy * ((1-dx)*bottom[0][c] + dx*bottom[1][c]);
  return pixel;
}

