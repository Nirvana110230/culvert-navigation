// A patch samples the original image at pyramid spacing. Validate the entire
// bilinear footprint (including the two neighbouring gradient samples) once.
struct PatchSampler
{
  int scale, left, top;
  std::ptrdiff_t row_step;
  float tl, tr, bl, br;

  bool init(const cv::Mat& img, const V2D& pc, int size, int level, bool gradient)
  {
    if (img.empty() || img.type() != CV_8UC1 || size <= 0 || level < 0 || level >= 30 ||
        !(pc.x() >= 0 && pc.x() < img.cols && pc.y() >= 0 && pc.y() < img.rows)) return false;
    scale = 1 << level;
    const float u_ref = pc.x(), v_ref = pc.y();
    if (static_cast<double>(u_ref) >= img.cols || static_cast<double>(v_ref) >= img.rows) return false;
    const int u = (static_cast<int>(u_ref) / scale) * scale;
    const int v = (static_cast<int>(v_ref) / scale) * scale;
    const std::int64_t lower = (size / 2 + std::int64_t(gradient)) * scale;
    const std::int64_t upper = (size - size / 2 + std::int64_t(gradient)) * scale;
    if (u < lower || v < lower || u + upper >= img.cols || v + upper >= img.rows) return false;
    left = u - (size / 2) * scale;
    top = v - (size / 2) * scale;
    row_step = static_cast<std::ptrdiff_t>(img.step[0]) * scale;
    const float x = (u_ref - u) / scale, y = (v_ref - v) / scale;
    tl = (1.0 - x) * (1.0 - y);
    tr = x * (1.0 - y);
    bl = (1.0 - x) * y;
    br = x * y;
    return true;
  }

  const uint8_t* row(const cv::Mat& img, int y) const
  {
    return img.ptr<uint8_t>(top + y * scale) + left;
  }

  float value(const uint8_t* p) const
  {
    return tl * p[0] + tr * p[scale] + bl * p[row_step] + br * p[row_step + scale];
  }
};

template<class Pixel>
bool bilinearInFrame(const cv::Mat& img, const Pixel& p)
{
  return p.x() >= 0 && p.y() >= 0 && p.x() < img.cols - 1 && p.y() < img.rows - 1;
}

bool inFrame(const cv::Mat& img, const V2D& px, int border)
{
  return px.x() >= border && px.y() >= border && px.x() < img.cols - border && px.y() < img.rows - border;
}

double centeredNcc(const float* a, double mean_a, const float* b, double mean_b, int size)
{
  double product = 0, energy_a = 0, energy_b = 0;
  for (int i = 0; i < size; ++i)
  {
    const double da = a[i] - mean_a, db = b[i] - mean_b;
    product += da * db;
    energy_a += da * da;
    energy_b += db * db;
  }
  const double denominator = std::sqrt(energy_a * energy_b);
  return denominator > 0 && std::isfinite(denominator) ? product / denominator : 0;
}

double patchMean(Feature& f, int size)
{
  if (!std::isfinite(f.mean_))
    f.mean_ = std::accumulate(f.patch_, f.patch_ + size, 0.0) / size;
  return f.mean_;
}
