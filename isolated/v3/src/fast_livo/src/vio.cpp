void VIOManager::maintainVisualMap()
{
  const double started = omp_get_wtime();
  // All consumers of retrieve_voxel_points, voxel_points, reference patch and
  // cached Jacobians finished before this call. Drop the borrows before eviction.
  if (!new_frame_->fts_.empty()) throw std::logic_error("unexpected owning Frame::fts_ in visual local map");
  visual_submap->reset();
  std::fill(retrieve_voxel_points.begin(), retrieve_voxel_points.end(), nullptr);
  sub_feat_map.clear();
  has_ref_patch_cache = false;

  const bool sample = last_memory_sample_s < 0 || started - last_memory_sample_s >= 1.0;
  memory_diagnostics::Resources resources;
  if (sample) {
    resources = memory_diagnostics::readResources();
    last_memory_sample_s = started;
  }
  last_maintenance = visual_lru::maintain(feat_map, new_frame_->pos(), frame_count-1, {}, lru_options,
                                          resources.shortfall(), sample);
  const auto& result = last_maintenance;
  retired_points += result.points_evicted;
  retired_features += result.features_evicted;
  pruned_observations += result.observations_pruned;
  pressure_retired_points += result.pressure_points_evicted;
  if (!sample) return;

  using namespace memory_diagnostics;
  static RollingCsv log("Log/visual_lru.csv",
      "frame,monotonic_s,visual_updates,visual_update_steps,used_points,voxels,points,features,patch_live_bytes,"
      "image_refs,images,image_bytes,active_images,history_images,blocked_points,borrowed_points,protected_images,"
      "protected_bytes,points_evicted_total,features_evicted_total,pruned_observations_total,pressure_points_total,"
      "images_created,images_released,images_last_ref_freed,bytes_last_ref_freed,images_detached_external_ref,"
      "bytes_detached_external_ref,external_image_refs,rss_bytes,mem_total_bytes,mem_available_bytes,mem_sample_valid,"
      "disk_free_bytes,system_shortfall_bytes,maintenance_ms");
  log.row() << std::setprecision(17) << frame_count << ',' << started << ',' << visual_update_frames << ',' << visual_update_steps << ','
      << total_points << ',' << feat_map.size() << ',' << points_created - points_deleted << ','
      << features_created - features_deleted << ',' << (features_created-features_deleted)*patch_size_total*sizeof(float) << ','
      << image_refs << ',' << images.size() << ',' << image_bytes << ',' << result.active_images << ','
      << images.size() - result.active_images << ',' << result.blocked_points << ',' << result.borrowed_points << ','
      << result.protected_images << ',' << result.protected_bytes << ',' << retired_points << ',' << retired_features << ','
      << pruned_observations << ',' << pressure_retired_points << ',' << images_created << ',' << images_released << ','
      << image_last_ref_freed << ',' << bytes_last_ref_freed << ',' << image_detached_external_ref << ','
      << bytes_detached_external_ref << ',' << external_images << ',' << resources.rss << ',' << resources.total << ','
      << resources.available << ',' << resources.memory_valid << ',' << resources.disk_free << ',' << resources.shortfall()
      << ',' << (omp_get_wtime()-started)*1000 << std::endl;
}
